export default function detectActionIntent(message = "") {
  const text = message.toLowerCase().trim();

  // رسائل قصيرة جداً أو تافهة → دردشة
  if (text.length < 3) return "chat_mode";

  /* ============================================================
     🟥 نوايا القراءة – read_file
     ============================================================ */
  if (/(اقر|اقرا|اقري|read|show|display|شوف|فرجيني|ورجيني|اعرض|عرض|شو فيه|محتوى|مضمون)/.test(text)) {
    return "read_file";
  }

  /* ============================================================
     🟦 نوايا الاستخراج – extract_file
     ============================================================ */
  if (/(استخرج|استخراج|extract|ocr|صور من|جداول من|نص من)/.test(text)) {
    return "extract_file";
  }

  /* ============================================================
     🟧 نوايا التحليل – analyze_file
     ============================================================ */
  if (/(حلل|تحليل|قيم|استنتج|استنتاج|نسبة|معدل|متوسط|اعلى|اقل|analysis|insight)/.test(text)) {
    return "analyze_file";
  }

  /* ============================================================
     🟨 نوايا التعديل – modify_file
     ============================================================ */
  if (/(عدل|غير|رتب|نظف|زبط|زبطلي|اضف|احذف|دمج|اعد كتابة|اعد بناء|modify|edit|fix)/.test(text)) {
    return "modify_file";
  }

  /* ============================================================
     🟩 نوايا التحويل – convert_file
     ============================================================ */
  if (/(حول|حوّل|صيغة|format|convert|pdf|word|excel|docx|xlsx|pptx)/.test(text)) {
    return "convert_file";
  }

  /* ============================================================
     🟪 نوايا التلخيص – summarize_file
     ============================================================ */
  if (/(لخص|ملخص|مختصر|بشكل عام|summary|brief)/.test(text)) {
    return "summarize_file";
  }

  /* ============================================================
     🟫 نوايا النقاش – discuss_file
     ============================================================ */
  if (/(ناقش|فسر|شرح|explain|discuss)/.test(text)) {
    return "discuss_file";
  }

  /* ============================================================
     🟦 نوايا الأوامر – command_mode
     ============================================================ */
  if (/(امسح|احذف الذاكرة|reset|clear|اعد التشغيل|restart)/.test(text)) {
    return "command_mode";
  }

  /* ============================================================
     🟪 إذا ما في نية واضحة → دردشة
     ============================================================ */
  return "chat_mode";
}

