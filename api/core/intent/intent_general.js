/**
 * api/core/intent/intent_general.js
 * Sovereign General Intent Engine – فهم النوايا العامة غير المتعلقة بالملفات
 */

export default function detectGeneralIntent(message = "") {
  const text = message.toLowerCase().trim();

  if (!text || text.length < 2) return "chat";

  /* ============================================================
     🌦️ نوايا الطقس – weather_query
     ============================================================ */
  if (/طقس|weather|حرارة|درجة الحرارة|جو|أمطار|رطوبة/.test(text)) {
    return "weather_query";
  }

  /* ============================================================
     🧍 نوايا الشخصيات – person_query
     ============================================================ */
  if (/من هو|مين هو|who is|سيرة|تعريف شخص/.test(text)) {
    return "person_query";
  }

  /* ============================================================
     📍 نوايا الأماكن – location_query
     ============================================================ */
  if (/وين تقع|اين تقع|where is|موقع|خارطة/.test(text)) {
    return "location_query";
  }

  /* ============================================================
     📚 نوايا التعريفات – definition_query
     ============================================================ */
  if (/ما هو|شو يعني|تعريف|explain|meaning/.test(text)) {
    return "definition_query";
  }

  /* ============================================================
     📰 نوايا الأخبار – news_query
     ============================================================ */
  if (/أخبار|news|حدث اليوم|شو صار/.test(text)) {
    return "news_query";
  }

  /* ============================================================
     ⚖️ نوايا المقارنة – compare_query
     ============================================================ */
  if (/قارن|مقارنة|أفضل من|vs|مقارنة بين/.test(text)) {
    return "compare_query";
  }

  /* ============================================================
     🎯 نوايا التوصيات – recommendation_query
     ============================================================ */
  if (/أفضل|نصحني|شو أختار|recommend|اقتراح/.test(text)) {
    return "recommendation_query";
  }

  /* ============================================================
     🔍 نوايا البحث الخارجي – general_search
     ============================================================ */
  if (/ابحث|بحث|جوجل|google|من النت|مصادر|رابط/.test(text)) {
    return "general_search";
  }

  /* ============================================================
     💬 إذا ما في نية واضحة → دردشة
     ============================================================ */
  return "chat";
    }
